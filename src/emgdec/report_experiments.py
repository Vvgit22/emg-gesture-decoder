"""Cross-experiment summary: one table, every number generated.

Reads artifacts/experiments/*/results.json (written by evaluate.build)
plus the participants dumps where they exist. Nothing is typed by hand.
Writes artifacts/experiments/SUMMARY.md + summary.json.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[2]
EXP = REPO / "artifacts" / "experiments"


def _cell(res: dict, model: str, config: str, kind: str) -> dict | None:
    return ((res.get("cells") or {}).get(model, {}).get(config, {})
            .get(kind))


def _participants(exp_dir: Path) -> dict | None:
    p = exp_dir / "participants.json"
    if not p.exists():
        return None
    d = json.loads(p.read_text())
    return ((d.get("kinds") or {}).get("cross_subject", {}).get("cnn", {})
            .get("summary"))


def main() -> None:
    lines = ["# Cross-experiment summary\n",
             "Window-level accuracy, mean ± SD over splits. "
             "Multi-seed rows show per-seed means and the SD across seeds. "
             "Generated by report_experiments.py — no hand numbers.\n"]
    summary = {"experiments": {}}
    exps = sorted(d.name for d in EXP.iterdir()
                  if (d / "results.json").exists())
    lines.append("| experiment | model | config | kind | folds | acc |"
                 " notes |")
    lines.append("|---|---|---|---|---|---|---|")
    for exp in exps:
        res = json.loads((EXP / exp / "results.json").read_text())
        entry = {"cells": {}}
        for model, cfgs in (res.get("cells") or {}).items():
            for config, kinds in cfgs.items():
                for kind, c in kinds.items():
                    notes = []
                    acc = f"{100*c['accuracy_mean']:.1f} ± {100*c['accuracy_std']:.1f}"
                    if "seeds" in c:
                        per = ", ".join(
                            f"s{s}={100*v['accuracy_mean']:.1f}"
                            for s, v in c["seeds"].items())
                        notes.append(
                            f"per-seed: {per}; across-seed SD "
                            f"{100*c['seed_std']:.2f}")
                    ps = (_participants(EXP / exp)
                          if (model == "cnn" and kind == "cross_subject")
                          else None)
                    if ps:
                        notes.append(
                            f"participant mean {100*ps['mean']:.1f}, SD "
                            f"{100*ps['sd']:.1f}, min {100*ps['min']:.1f}, "
                            f"p5 {100*ps['p5']:.1f}, <70%: {ps['below70']}")
                    lines.append(
                        f"| {exp} | {model} | {config} | {kind} | "
                        f"{c['n_splits']} | {acc} | {'; '.join(notes)} |")
                    entry["cells"].setdefault(model, {}).setdefault(
                        config, {})[kind] = {**c, "notes": notes}
        summary["experiments"][exp] = entry
    # paired causal vs offline_v1b seed0 fold accuracies
    try:
        a = json.loads((EXP/"causal_v1"/"results.json").read_text())
        b = json.loads((EXP/"offline_v1b"/"results.json").read_text())
        ca = a["cells"]["cnn"]["both"]["cross_subject"]
        ob = b["cells"]["cnn"]["both"]["cross_subject"]
        lines.append("\n## causal vs offline_v1b (per-fold paired, seed 0)\n")
        for i, (rc, ro) in enumerate(zip(
                _folds("causal_v1"), _folds("offline_v1b"))):
            d = (rc["acc"] - ro["acc"]) * 100
            lines.append(f"- fold{i}: causal {100*rc['acc']:.1f} vs offline "
                         f"{100*ro['acc']:.1f} → Δ {d:+.1f} pp")
        ds = [ (rc["acc"]-ro["acc"])*100 for rc, ro in zip(
            _folds("causal_v1"), _folds("offline_v1b"))]
        lines.append(f"\nmean paired difference: {np.mean(ds):+.2f} pp "
                     f"(SD {np.std(ds, ddof=1):.2f})")
        lines.append(f"\npooled: causal {100*ca['accuracy_mean']:.1f}% vs "
                     f"offline seed0 {100*_seed0(ob):.1f}%")
    except Exception as e:
        lines.append(f"\n(paired causal/offline comparison skipped: {e})")
    # machine-readable extras for the website's robustness table
    try:
        a = json.loads((EXP/"causal_v1"/"results.json").read_text())
        b = json.loads((EXP/"offline_v1b"/"results.json").read_text())
        pf = [(rc["acc"], ro["acc"]) for rc, ro in
              zip(_folds("causal_v1"), _folds("offline_v1b"))]
        ds = [c - o for c, o in pf]
        summary["comparisons"] = {"causal_vs_offline": {
            "per_fold": [{"causal": c, "offline": o, "delta": c - o}
                         for c, o in pf],
            "mean_delta": float(np.mean(ds)),
            "sd_delta": float(np.std(ds, ddof=1))}}
    except Exception:
        pass
    for exp in exps:
        p = EXP / exp / "participants.json"
        if p.exists():
            summ = (json.loads(p.read_text())["kinds"]["cross_subject"]
                    ["cnn"]["summary"])
            summary["experiments"][exp]["participants"] = summ
    cal = EXP / "protocol_v1_analysis" / "calibration.json"
    if cal.exists():
        d = json.loads(cal.read_text())["models"]["cross_subject"]
        raw_ece = [c["raw"]["ece"] for c in d.values()]
        cal_ece = [c["calibrated"]["ece"] for c in d.values()]
        summary["calibration"] = {
            "ece_raw_min": min(raw_ece), "ece_raw_max": max(raw_ece),
            "ece_cal_min": min(cal_ece), "ece_cal_max": max(cal_ece)}
    per = EXP / "protocol_v1_analysis" / "perturbations.json"
    if per.exists():
        d = json.loads(per.read_text())["folds"]
        keys = list(d["fold0"])
        summary["perturbations"] = {
            k: float(np.mean([f[k] for f in d.values()])) for k in keys}
    for exp in exps:
        res = json.loads((EXP / exp / "results.json").read_text())
        for model, cfgs in (res.get("cells") or {}).items():
            for config, kinds in cfgs.items():
                for kind, c in kinds.items():
                    if "seeds" in c:
                        summary["experiments"][exp]["cells"][model][
                            config][kind]["per_seed"] = [
                            {"seed": s, "accuracy_mean": v["accuracy_mean"]}
                            for s, v in c["seeds"].items()]
    (EXP / "SUMMARY.md").write_text("\n".join(lines))
    (EXP / "summary.json").write_text(json.dumps(summary, indent=1))
    print("\n".join(lines))


def _folds(exp: str) -> list[dict]:
    runs = sorted((EXP / exp / "runs" / "cnn" / "both" / "cross_subject")
                  .glob("fold?.json"))
    out = []
    for f in runs:
        d = json.loads(f.read_text())
        cm = np.asarray(d["confusion"])
        out.append({"name": f.stem, "acc": float(np.diag(cm).sum()/cm.sum())})
    return out


def _seed0(cell: dict) -> float:
    if "seeds" in cell and "0" in cell["seeds"]:
        return cell["seeds"]["0"]["accuracy_mean"]
    return cell["accuracy_mean"]


if __name__ == "__main__":
    main()
